#!/usr/bin/env node
/**
 * Reads .env (and real environment variables, which win) and writes config.js
 * so the plain browser JS can know the API URLs. No dependencies needed.
 *
 *   node scripts/generate-config.js
 */
const fs = require("fs");
const path = require("path");
 
const root = path.join(__dirname, "..");
const envFile = path.join(root, ".env");
 
function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}
 
const fileEnv = fs.existsSync(envFile) ? parseEnv(fs.readFileSync(envFile, "utf8")) : {};
const get = (key, fallback = "") => process.env[key] ?? fileEnv[key] ?? fallback;
const trimSlash = (url) => url.replace(/\/+$/, "");
 
const config = {
  API_BASE_URL: trimSlash(get("API_BASE_URL")),
  API_BASE_URL_LOCAL: trimSlash(get("API_BASE_URL_LOCAL", "http://127.0.0.1:8000")),
  API_BASE_URL_PROD: trimSlash(get("API_BASE_URL_PROD")),
  DEFAULT_TOP_K: Number(get("DEFAULT_TOP_K", "4")) || 4,
};
 
const banner = "// Generated by scripts/generate-config.js from .env. Do not edit by hand.\n";
fs.writeFileSync(path.join(root, "config.js"), `${banner}window.APP_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
 
if (!fs.existsSync(envFile)) console.warn("No .env found; used environment variables and defaults.");
console.log("config.js written:", config);
 